"""Stroke templates for digits, Latin letters and a little punctuation.

Why these exist
---------------
`hanzi-lookup` ships median stroke data for 9507 Chinese characters and nothing else: Han characters
are the only script with a public stroke-order corpus, so there is no equivalent `mmah.json` for
`0-9` / `A-Z` / `a-z`.  Without a repository entry a character simply cannot be matched - the
matcher scans what the data contains, so writing a `4` finds Chinese characters or nothing.

So these are *authored* templates, not imported data, and they are written down as the thing they
are: a canonical single-stroke skeleton per glyph, the way the glyph is normally written, expressed
in a unit box (x right, y **down**, 0 = left/top, 1 = right/bottom) using the usual metrics

    cap height top 0.18      x-height top 0.45
    baseline       0.80      descender    0.95

Round glyphs ("0", "O", "o", "Q", "8") are drawn with a small gap rather than closed: a perfectly closed
loop becomes a single sub-stroke whose start and end coincide, which quantizes to length 0 - and a
stored length of 0 makes the matcher compute NaN, so the character could never match at all.

They are fed through the very same analyzer + packer as the Chinese data
(`hanzi_encode.py`), so a repository built from them is interchangeable with `mmah.json`.

Two properties are deliberate:

* **The centres are computed with the analyzer's formula, not the offline generator's.**  The
  shipped Chinese file stores each sub-stroke centre as its *absolute* position in the canvas
  divided by the character diagonal (see `hanzi_encode.CENTER_MODE_CONVERTER`), whereas input
  strokes are analysed into *bounding-box relative* centres.  For Han characters, which fill the
  256x256 box, the two nearly coincide.  Latin letters do not fill it - a lowercase `o` occupies a
  small box near the middle - so absolute centres would put every template ~7 nibbles away from what
  the recognizer computes for user input.  Using the analyzer's own formula removes that bias.
* **Point spacing is human, not uniform.**  Templates carry 2-9 points per stroke, like the median
  data.  A user stroke is re-sampled to a uniform spacing before analysis anyway
  (`stroke_preprocess.py`), and the two segmentation styles agree because both are compared by the
  analyzer's pivot detector.

`build_alnum.py` encodes these; `check_alnum.py` verifies the result by writing each template back
as simulated handwriting and requiring the glyph to come back on top.
"""

